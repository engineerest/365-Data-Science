# Data Types

import numpy as np

# Ndarrays

array_a = np.array([1, 2, 3])
print(array_a)

print(type(array_a))

print(array_a.shape)

array_b = np.array([[7, 8, 9], [10, 11, 12]])

print(type(array_b))

print(array_b)

print(array_b.shape[1])

array_c = np.array(13)

print(type(array_c))

print(array_c)

print(array_c.shape)
# A single point in N-dimensional space

array_d = np.array([15])

print(type(array_d))

print(array_d)

print(array_d.shape)

array_e = np.array([[15]])
print(array_e)

# ndarrays:
# Single Scalars
# Sequences of numbers
# Tables of values
# Computationally stable
# Universally accepted in the Python community
# Syntax closely resembles another data type